create table if not exists public.series (
  id bigint generated by default as identity primary key,
  slug text unique not null,
  name text not null,
  description text,
  is_featured boolean not null default false,
  created_at timestamptz not null default now()
);

alter table public.articles
  add column if not exists series_id bigint references public.series(id) on delete set null;

create index if not exists articles_series_id_idx on public.articles(series_id);
create unique index if not exists series_single_featured_idx on public.series(is_featured) where is_featured;

alter table public.series enable row level security;

create policy "series are public" on public.series
for select to anon, authenticated using (true);

create policy "admins can manage series" on public.series
for all to authenticated
using (((select auth.jwt()) -> 'app_metadata' ->> 'role') = 'admin')
with check (((select auth.jwt()) -> 'app_metadata' ->> 'role') = 'admin');

grant select on public.series to anon, authenticated;
grant insert, update, delete on public.series to authenticated;
